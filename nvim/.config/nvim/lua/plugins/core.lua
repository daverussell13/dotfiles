local sessions_sidebar

local function toggle_sessions_sidebar()
  local widgets = require("dap.ui.widgets")
  if not sessions_sidebar then
    sessions_sidebar = widgets.sidebar(widgets.sessions, {}, "5 sp | setl winfixheight")
  end

  local wins_before = vim.api.nvim_tabpage_list_wins(0)
  sessions_sidebar.toggle()
  local wins_after = vim.api.nvim_tabpage_list_wins(0)

  if #wins_after > #wins_before then
    for _, w in ipairs(wins_after) do
      if not vim.tbl_contains(wins_before, w) then
        vim.api.nvim_set_current_win(w)
        local buf = vim.api.nvim_win_get_buf(w)
        vim.keymap.set("n", "q", function()
          sessions_sidebar.close()
        end, { buffer = buf, nowait = true, silent = true })
      end
    end
  end
end

